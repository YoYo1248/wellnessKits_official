// Auto Detection Logic
export function getPreferredLanguage() {
  const saved = localStorage.getItem('wellnesskits_lang');
  if (saved && translations[saved]) {
    return saved;
  }

  const navLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
  
  if (navLang.startsWith('zh-tw') || navLang.startsWith('zh-hk') || navLang.startsWith('zh-mo')) {
    return 'zh-TW';
  }
  if (navLang.startsWith('zh')) {
    return 'zh-CN';
  }
  if (navLang.startsWith('es')) {
    return 'es';
  }

  return 'en';
}

// Language Change Dispatcher
export function setLanguage(lang) {
  if (!translations[lang]) return;
  localStorage.setItem('wellnesskits_lang', lang);
  document.documentElement.lang = lang;
  applyTranslations(lang);
  updateLanguageDropdownUI(lang);
}

// Apply Translations to DOM
export function applyTranslations(lang) {
  const dict = translations[lang] || translations.en;
  
  // Find all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });
}

// UI Dropdown Controller
function updateLanguageDropdownUI(lang) {
  const select = document.getElementById('language-select');
  if (select) {
    select.value = lang;
  }
}

// Initialize i18n Engine
export function initI18n() {
  const currentLang = getPreferredLanguage();
  document.documentElement.lang = currentLang;

  // Insert Language Switcher in Navbars dynamically
  const navContainers = document.querySelectorAll('.nav-container');
  navContainers.forEach(nav => {
    if (!nav.querySelector('.lang-switcher')) {
      const switcher = document.createElement('div');
      switcher.className = 'lang-switcher';
      switcher.style.cssText = 'display: inline-flex; align-items: center; gap: 4px; margin-left: 10px; flex-shrink: 0;';
      switcher.innerHTML = `
        <span style="font-size: 0.95rem;">🌐</span>
        <select id="language-select" class="lang-dropdown" aria-label="Select Language" style="
          background: var(--bg-card);
          border: 1px solid var(--border-warm);
          color: var(--text-main);
          padding: 4px 8px;
          border-radius: 8px;
          font-size: 0.82rem;
          font-weight: 600;
          cursor: pointer;
          font-family: inherit;
          outline: none;
        ">
          <option value="en">English</option>
          <option value="zh-CN">简体中文</option>
          <option value="zh-TW">繁體中文</option>
          <option value="es">Español</option>
        </select>
      `;
      nav.appendChild(switcher);

      const selectEl = switcher.querySelector('#language-select');
      selectEl.addEventListener('change', (e) => {
        setLanguage(e.target.value);
      });
    }
  });

  applyTranslations(currentLang);
  updateLanguageDropdownUI(currentLang);
}

// Auto-run on DOMContentLoaded
if (typeof window !== 'undefined') {
  document.addEventListener('DOMContentLoaded', () => {
    initI18n();
  });
}
